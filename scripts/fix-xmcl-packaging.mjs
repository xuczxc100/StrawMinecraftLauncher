// @xmcl/unzip@2.2.0 was published with "main": "./index.ts" (not shipped) and no dist/index.mjs,
// so every package depending on it (@xmcl/core, @xmcl/installer) fails to load. Point it at dist/.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const fixes = [
  {
    pkg: '@xmcl/unzip',
    fields: { main: './dist/index.js', types: './dist/index.d.ts', module: undefined },
  },
]

// @xmcl/installer@6.3.x requires "@xmcl/core/utils", which @xmcl/core@2.16.x does not ship.
const CORE_UTILS_SHIM = `'use strict'
// Generated by scripts/fix-xmcl-packaging.mjs
const { access } = require('node:fs/promises')
const { checksum } = require('./dist/index.js')
const exists = (file) => access(file).then(() => true, () => false)
exports.checksum = checksum
exports.exists = exists
exports.isNotNull = (v) => v !== undefined && v !== null
exports.validateSha1 = async (target, hash, strict = false) => {
  if (!(await exists(target))) return false
  if (!hash) return !strict
  return (await checksum(target, 'sha1')) === hash
}
`
const coreDir = join(root, 'node_modules', '@xmcl', 'core')
const shimPath = join(coreDir, 'utils.js')
if (existsSync(join(coreDir, 'dist', 'index.js')) && !existsSync(join(coreDir, 'dist', 'utils.js'))) {
  if (!existsSync(shimPath) || readFileSync(shimPath, 'utf8') !== CORE_UTILS_SHIM) {
    writeFileSync(shimPath, CORE_UTILS_SHIM)
    console.log('fix-xmcl-packaging: wrote @xmcl/core/utils shim')
  }
}

for (const { pkg, fields } of fixes) {
  const file = join(root, 'node_modules', pkg, 'package.json')
  if (!existsSync(file)) continue
  const json = JSON.parse(readFileSync(file, 'utf8'))
  let changed = false
  for (const [key, value] of Object.entries(fields)) {
    if (value === undefined) {
      if (key in json && !existsSync(join(dirname(file), json[key]))) {
        delete json[key]
        changed = true
      }
    } else if (json[key] !== value && existsSync(join(dirname(file), value))) {
      json[key] = value
      changed = true
    }
  }
  if (changed) {
    writeFileSync(file, JSON.stringify(json, null, 2) + '\n')
    console.log(`fix-xmcl-packaging: patched ${pkg}`)
  }
}
